from decimal import Decimal as D, localcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parent
METRICS = ("grad_previous_abs_dot", "grad_current_abs_dot", "ce_abs_difference",
           "kl_new_old", "kl_old_new")


def decjson(x):
    if isinstance(x, D):
        return str(x)
    if isinstance(x, dict):
        return {k: decjson(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [decjson(v) for v in x]
    return x


def dump(path, obj):
    with path.open("x") as f:
        json.dump(decjson(obj), f, indent=2, ensure_ascii=False, allow_nan=False)
        f.write("\n")


def sigmoid(z):
    return D(1) / (D(1) + (-z).exp())


def logit(p):
    return (p / (1-p)).ln()


def ce(z, y):
    # Separate direct-loss expression, also used by finite-difference tests.
    return (D(1) + z.exp()).ln() - D(y)*z


def entropy(p):
    return -p*p.ln() - (1-p)*(1-p).ln()


def ssd(xs):
    mean = sum(xs, D(0)) / len(xs)
    return sum(((x-mean)**2 for x in xs), D(0))


def relation(a, b):
    return "A>B" if a > b else "A<B" if a < b else "tie"


def compare(a, b):
    ra = relation(*a)
    rb = relation(*b)
    if ra == "tie" or rb == "tie":
        return "both_tie" if ra == rb else "one_tie"
    return "concordant" if ra == rb else "reversal"


def step_metrics(z0, z1, y):
    p = sigmoid(z0)
    q = sigmoid(z1)
    dz = z1-z0
    # Log-partition difference, evaluated with high precision.
    da = (1+p*(dz.exp()-1)).ln()
    signed_ce = da-D(y)*dz
    values = {
        "z_previous": z0, "z_current": z1,
        "p_previous": p, "p_current": q, "delta_logit": dz,
        "ce_signed_difference": signed_ce,
        "gradient_previous_signed_dot": (p-D(y))*dz,
        "gradient_current_signed_dot": (q-D(y))*dz,
        "grad_previous_abs_dot": abs((p-D(y))*dz),
        "grad_current_abs_dot": abs((q-D(y))*dz),
        "ce_abs_difference": abs(signed_ce),
        "kl_new_old": q*dz-da,
        "kl_old_new": da-p*dz,
        "kl_quadratic_previous": p*(1-p)*dz*dz/2,
        "entropy_previous": entropy(p), "entropy_current": entropy(q),
        "fisher_previous": p*(1-p),
        "ce_direct_difference": ce(z1, y)-ce(z0, y),
        "kl_new_old_direct": q*(q/p).ln()+(1-q)*((1-q)/(1-p)).ln(),
        "kl_old_new_direct": p*(p/q).ln()+(1-p)*((1-p)/(1-q)).ln(),
    }
    # Independent binary64 path. No clipping or hidden replacement of zeros.
    zp, delta = float(z0), float(dz)
    pf = 1/(1+math.exp(-zp))
    qf = 1/(1+math.exp(-(zp+delta)))
    af = math.log1p(pf*math.expm1(delta))
    values["binary64"] = {
        "grad_previous_abs_dot": abs((pf-y)*delta),
        "grad_current_abs_dot": abs((qf-y)*delta),
        "ce_abs_difference": abs(af-y*delta),
        "kl_new_old": qf*delta-af,
        "kl_old_new": af-pf*delta,
    }
    return values


def trace(spec):
    p0 = [D(x) for x in spec["p0"]]
    a = [D(x) for x in spec["slopes"]]
    ys = spec["y"]
    offsets = [logit(p) for p in p0]
    ws = [D(0)]
    updates = []
    if spec["kind"] == "prescribed":
        for n in spec["increments"]:
            ws.append(ws[-1]+D(n)*D(spec["epsilon"]))
    else:
        eta = D(spec["eta"])
        for _ in range(spec["steps"]):
            w = ws[-1]
            grad = sum((ai*(sigmoid(bi+ai*w)-yi)
                        for ai, bi, yi in zip(a, offsets, ys)), D(0))
            ws.append(w-eta*grad)
            updates.append({"w_previous":w, "gradient_sum":grad,
                            "eta":eta, "w_current":ws[-1],
                            "objective_previous":sum((ce(bi+ai*w, yi) for ai,bi,yi in zip(a,offsets,ys)),D(0)),
                            "objective_current":sum((ce(bi+ai*ws[-1], yi) for ai,bi,yi in zip(a,offsets,ys)),D(0))})
    samples = []
    for idx, (ai, bi, yi) in enumerate(zip(a, offsets, ys)):
        samples.append({"sample": "AB"[idx], "y":yi, "slope":ai,
                        "offset":bi, "steps":[step_metrics(bi+ai*u, bi+ai*v, yi)
                                                for u,v in zip(ws[:-1],ws[1:])]})
    return {"spec":spec, "shared_parameter_states":ws,
            "optimizer_updates":updates, "samples":samples}


def make_specs(protocol):
    specs = []
    for case in protocol["prescribed_cases"]:
        for eps in protocol["epsilons"]:
            spec = dict(case, kind="prescribed", epsilon=eps)
            spec["case_id"] = case["id"]+"_eps_"+eps
            specs.append(spec)
    gd = protocol["actual_GD"]
    for labels, eta in itertools.product(gd["labels"], gd["learning_rates"]):
        specs.append({"kind":"actual_GD", "id":"GD_"+"".join(map(str,labels)),
                      "case_id":"GD_"+"".join(map(str,labels))+"_eta_"+eta,
                      "p0":gd["p0"], "slopes":gd["slopes"], "y":labels,
                      "eta":eta, "steps":gd["steps"], "role":"optimizer_control"})
    return specs


def windows_for(case, protocol):
    spec = case["spec"]
    steps = len(case["samples"][0]["steps"])
    lengths = sorted(set([2,steps])) if spec["kind"] == "prescribed" else protocol["actual_GD"]["windows"]
    etas = protocol["common_eta_normalizations"] if spec["kind"] == "prescribed" else [spec["eta"]]
    result = []
    for length, eta_text in itertools.product(lengths, etas):
        eta = D(eta_text)
        for end in range(length,steps+1):
            vals = {}
            floats = {}
            for metric in METRICS:
                vals[metric] = [ssd([r[metric]/eta for r in sample["steps"][end-length:end]])
                                for sample in case["samples"]]
                floats[metric] = []
                for sample in case["samples"]:
                    xs = [r["binary64"][metric]/float(eta) for r in sample["steps"][end-length:end]]
                    mean = math.fsum(xs)/length
                    floats[metric].append(math.fsum((x-mean)**2 for x in xs))
            result.append({"case_id":spec["case_id"], "kind":spec["kind"],
                           "window_length":length, "end_step":end,
                           "common_eta_divisor":eta_text,
                           "ssd":vals, "population_variance":{m:[v/length for v in pair] for m,pair in vals.items()},
                           "binary64_ssd":floats,
                           "relations":{m:relation(*vals[m]) for m in METRICS},
                           "binary64_relations":{m:relation(*floats[m]) for m in METRICS},
                           "comparisons":{m+"_vs_"+k:compare(vals[m],vals[k])
                                          for m in METRICS[:3] for k in METRICS[3:]}})
    return result


def ema_for(windows, protocol):
    result=[]
    groups={}
    for row in windows:
        key=(row["case_id"],row["window_length"],row["common_eta_divisor"])
        groups.setdefault(key,[]).append(row)
    for (case_id,length,eta),rows in groups.items():
        for b in protocol["ema_new_weights"]:
            beta=D(b)
            state={m:[D(0),D(0)] for m in METRICS}
            for row in rows:
                state={m:[beta*v+(1-beta)*old for v,old in zip(row["ssd"][m],state[m])] for m in METRICS}
                result.append({"case_id":case_id,"window_length":length,"common_eta_divisor":eta,
                               "beta_new_weight":b,"initialization":"zero_assumed_not_author_default",
                               "end_step":row["end_step"],"ema":state,
                               "comparisons":{m+"_vs_"+k:compare(state[m],state[k]) for m in METRICS[:3] for k in METRICS[3:]}})
    return result


def precision_summary(high, low):
    maxima={m:D(0) for m in METRICS}
    maxima64={m:0.0 for m in METRICS}
    worst64={m:None for m in METRICS}
    for h,l in zip(high,low):
        for hs,ls in zip(h["samples"],l["samples"]):
            for i,(hr,lr) in enumerate(zip(hs["steps"],ls["steps"])):
                for m in METRICS:
                    if hr[m]:
                        maxima[m]=max(maxima[m],abs(lr[m]-hr[m])/abs(hr[m]))
                        err=abs(hr["binary64"][m]-float(hr[m]))/abs(float(hr[m]))
                        if err>maxima64[m]:
                            maxima64[m]=err
                            worst64[m]={"case_id":h["spec"]["case_id"],"sample":hs["sample"],"step":i+1}
    return {"decimal_60_vs_90_max_relative_error":maxima,
            "binary64_vs_decimal90_max_relative_error":maxima64,
            "binary64_worst_cases":worst64,
            "zero_reference_handling":"excluded from relative error; zero controls checked separately"}


def summarize(cases, windows, ema, precision):
    primary=[]
    controls={}
    for row in windows:
        if row["kind"]=="prescribed" and row["common_eta_divisor"]=="1" and row["window_length"]==2 and row["end_step"]==2:
            if row["case_id"].startswith("primary_positive_two_"):
                primary.append(row)
            key=row["case_id"].rsplit("_eps_",1)[0]
            outcome=row["comparisons"]["ce_abs_difference_vs_kl_new_old"]
            controls.setdefault(key,{})[outcome]=controls.setdefault(key,{}).get(outcome,0)+1
    gd=[]
    for c in cases:
        if c["spec"]["kind"]!="actual_GD":continue
        ws=[w for w in windows if w["case_id"]==c["spec"]["case_id"]]
        by_length={}
        for length in sorted(set(w["window_length"] for w in ws)):
            outcomes={}
            for w in ws:
                if w["window_length"]==length:
                    o=w["comparisons"]["ce_abs_difference_vs_kl_new_old"]
                    outcomes[o]=outcomes.get(o,0)+1
            by_length[str(length)]=outcomes
        gd.append({"case_id":c["spec"]["case_id"],"label_pair":c["spec"]["y"],
                   "eta":c["spec"]["eta"],"all_windows_CE_vs_source_KL":by_length,
                   "objective_monotone":all(u["objective_current"]<=u["objective_previous"] for u in c["optimizer_updates"])})
    slopes=[]
    for left,right in zip(primary[:-1],primary[1:]):
        e1=float(left["case_id"].split("_eps_")[1]);e2=float(right["case_id"].split("_eps_")[1])
        slopes.append({"epsilon_pair":[e1,e2],"variance_loglog_slopes":{
            m:[math.log(float(v2/v1))/math.log(e2/e1) for v1,v2 in zip(left["ssd"][m],right["ssd"][m])]
            for m in METRICS}})
    mismatches=[]
    for row in windows:
        for m in METRICS:
            if row["relations"][m]!=row["binary64_relations"][m]:
                mismatches.append({"case_id":row["case_id"],"window_length":row["window_length"],
                                   "end_step":row["end_step"],"eta_divisor":row["common_eta_divisor"],
                                   "metric":m,"decimal90":row["relations"][m],"binary64":row["binary64_relations"][m]})
    return {"scope":"formula audit only; no recovered SADA controller or empirical generalization test",
            "case_count":len(cases),"window_count":len(windows),"ema_record_count":len(ema),
            "primary_two_step":primary,"prescribed_first_two_step_controls":controls,
            "actual_GD_controls":gd,"asymptotics":slopes,"precision":precision,
            "binary64_rank_mismatches":mismatches,
            "action_mapping_status":"not executed; source is incomplete",
            "next_gate":"NO-GO for training or contribution claim; parent review and fuller controller/prior evidence required"}


def run(out):
    started=time.process_time()
    protocol=json.loads((ROOT/'protocol.json').read_text())
    specs=make_specs(protocol)
    out.mkdir(exist_ok=False,parents=True)
    all_cases=[]
    for digits in protocol['precision_digits']:
        cases=[]
        with localcontext() as ctx:
            ctx.prec=digits
            for spec in specs:
                if time.process_time()-started>protocol['compute_budget_cpu_seconds']:
                    raise RuntimeError('CPU budget exceeded; stop')
                cases.append(trace(spec))
        all_cases.append(cases)
    cases,low=all_cases
    with localcontext() as ctx:
        ctx.prec=protocol['precision_digits'][0]
        windows=[w for c in cases for w in windows_for(c,protocol)]
        ema=ema_for(windows,protocol)
        precision=precision_summary(cases,low)
        summary=summarize(cases,windows,ema,precision)
        import test_audit
        tests=test_audit.validate(cases,windows,precision,protocol)
    for name,records in [('raw-cases.jsonl',cases),('windows.jsonl',windows),('ema.jsonl',ema)]:
        with (out/name).open('x') as f:
            for record in records:f.write(json.dumps(decjson(record),ensure_ascii=False,allow_nan=False)+'\n')
    with (out/'window-summary.csv').open('x',newline='') as f:
        writer=csv.writer(f)
        writer.writerow(['case_id','kind','L','end_step','eta_divisor','metric','A_ssd','B_ssd','ordering'])
        for w in windows:
            for m in METRICS:writer.writerow([w['case_id'],w['kind'],w['window_length'],w['end_step'],w['common_eta_divisor'],m,*w['ssd'][m],w['relations'][m]])
    dump(out/'numeric-summary.json',summary)
    dump(out/'test-results.json',tests)
    metadata={'python':sys.version,'platform':platform.platform(),'machine':platform.machine(),
              'computation_cpu_seconds':time.process_time()-started,'third_party_packages_used':[],
              'network_used_by_audit_script':False,'project_data_read':False,
              'script_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              'tests_sha256':hashlib.sha256((ROOT/'test_audit.py').read_bytes()).hexdigest(),
              'protocol_sha256':hashlib.sha256((ROOT/'protocol.json').read_bytes()).hexdigest()}
    dump(out/'run-metadata.json',metadata)
    print(json.dumps(decjson({'case_count':len(cases),'windows':len(windows),
                             'tests':tests,'cpu_seconds':metadata['computation_cpu_seconds'],
                             'primary_epsilon_0.01':[p for p in summary['primary_two_step'] if p['case_id'].endswith('_eps_0.01')],
                             'actual_GD_controls':summary['actual_GD_controls'],
                             'precision':precision,'binary64_rank_mismatches':len(summary['binary64_rank_mismatches'])}),indent=2))
    return 0 if tests['failed']==0 else 1


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,required=True,help='A NEW output directory; existing files never overwritten')
    args=parser.parse_args()
    raise SystemExit(run(args.out))
