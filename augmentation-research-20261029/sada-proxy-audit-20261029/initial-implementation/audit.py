"""Stdlib-only SADA v1 formula audit. Never imports project code or data.

Reproduce into a NEW directory: python3 audit.py --out /tmp/sada-audit-recheck
Prescribed trajectories are not asserted to be generated by an optimizer.
The actual-GD controls minimize a two-observation scalar logistic objective.
All numbers are toy calculations, not image-training/generalization evidence.
"""
